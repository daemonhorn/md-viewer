//! Request handling for the `mdv://` protocol (independent of wry for testability).

use std::path::{Path, PathBuf};

use crate::page::{self, Theme};
use crate::sandbox::{self, SandboxError};

/// Origin of the custom protocol: wry maps `mdv` to `http://mdv.localhost` on
/// Windows and `mdv://localhost` elsewhere.
#[cfg(windows)]
pub const BASE: &str = "http://mdv.localhost";
#[cfg(not(windows))]
pub const BASE: &str = "mdv://localhost";

/// CSP for user files (images, svg, pdf...). Even when such a file is loaded as a
/// top-level document (e.g. an svg), `sandbox` keeps scripts from running.
pub const FILE_CSP: &str = "default-src 'none'; img-src 'self'; style-src 'unsafe-inline'; sandbox";

/// CSP for pages and assets generated by the app. `'self'` is listed together with
/// the explicit origin because custom-scheme origins are opaque on some engines.
pub fn app_csp(base: &str, allow_remote_images: bool) -> String {
    let remote = if allow_remote_images { " https:" } else { "" };
    format!(
        "default-src 'none'; script-src 'self' {base}; style-src 'self' {base} 'unsafe-inline'; \
         img-src 'self' {base} data:{remote}; media-src 'self' {base}; font-src 'self' {base}; \
         connect-src 'self' {base}; base-uri 'none'; form-action 'none'; frame-ancestors 'none'"
    )
}

/// Messages the page may send over wry's IPC channel.
#[derive(Debug, PartialEq, Eq)]
pub enum IpcAction {
    Print,
}

/// Decide what an IPC message means. Only the exact body `print` sent from a page
/// served by our own origin is accepted; everything else is ignored.
pub fn ipc_action(url: &str, body: &str) -> Option<IpcAction> {
    ipc_action_for(BASE, url, body)
}

fn ipc_action_for(base: &str, url: &str, body: &str) -> Option<IpcAction> {
    if body != "print" || url.eq_ignore_ascii_case("about:blank") {
        return None;
    }
    (classify_nav(url, base) == Nav::Internal).then_some(IpcAction::Print)
}

#[derive(Debug, PartialEq, Eq)]
pub enum Nav {
    /// Navigate inside the webview.
    Internal,
    /// Hand to the system browser/mail client.
    External,
    /// Cancel.
    Deny,
}

/// Decide what to do with a top-level navigation to `url`, given the app `base`
/// origin. Only markdown files and directories may load in the webview; the
/// authority must match exactly (no userinfo, port or suffix tricks).
pub fn classify_nav(url: &str, base: &str) -> Nav {
    let lower = url.to_ascii_lowercase();
    if lower == "about:blank" {
        return Nav::Internal;
    }
    let (Some((bscheme, bhost)), Some((scheme, rest))) =
        (base.split_once("://"), url.split_once("://"))
    else {
        return if lower.starts_with("mailto:") {
            Nav::External
        } else {
            Nav::Deny
        };
    };
    if scheme.eq_ignore_ascii_case(bscheme) {
        let end = rest.find(['/', '?', '#']).unwrap_or(rest.len());
        let (authority, tail) = rest.split_at(end);
        if !authority.eq_ignore_ascii_case(bhost) {
            return if scheme.eq_ignore_ascii_case("http") {
                Nav::External
            } else {
                Nav::Deny
            };
        }
        let path = tail.split(['?', '#']).next().unwrap_or("");
        let decoded = percent_encoding::percent_decode_str(path).decode_utf8_lossy();
        return if decoded.is_empty()
            || decoded.ends_with('/')
            || is_markdown(Path::new(decoded.as_ref()))
        {
            Nav::Internal
        } else {
            Nav::Deny
        };
    }
    if scheme.eq_ignore_ascii_case("http") || scheme.eq_ignore_ascii_case("https") {
        Nav::External
    } else {
        Nav::Deny
    }
}

pub struct State {
    /// Sandbox root: the opened document's directory.
    pub root: Option<PathBuf>,
    /// Document most recently served (used for live reload).
    pub current: Option<PathBuf>,
    pub raw_default: bool,
    pub theme: Theme,
    /// Add `https:` to the img-src CSP (`--allow-remote-images`).
    pub allow_remote_images: bool,
}

pub struct Reply {
    pub status: u16,
    pub mime: &'static str,
    pub body: Vec<u8>,
    /// `Content-Security-Policy` header value (filled in by `handle`).
    pub csp: String,
    /// Generated by the app (true) vs. a user file (false).
    app: bool,
}

impl Reply {
    fn html(status: u16, s: String) -> Self {
        Reply {
            status,
            mime: "text/html; charset=utf-8",
            body: s.into_bytes(),
            csp: String::new(),
            app: true,
        }
    }
    fn text(status: u16, s: &str) -> Self {
        Reply {
            status,
            mime: "text/plain; charset=utf-8",
            body: s.as_bytes().to_vec(),
            csp: String::new(),
            app: true,
        }
    }
    pub fn error(status: u16, s: &str) -> Self {
        Self::text(status, s)
    }
    fn asset(mime: &'static str, body: Vec<u8>) -> Self {
        Reply {
            status: 200,
            mime,
            body,
            csp: String::new(),
            app: true,
        }
    }
}

pub fn is_markdown(p: &Path) -> bool {
    matches!(
        p.extension()
            .and_then(|e| e.to_str())
            .map(str::to_ascii_lowercase)
            .as_deref(),
        Some("md" | "markdown" | "mdown" | "mkd" | "mdx")
    )
}

pub fn mime_for(p: &Path) -> &'static str {
    match p
        .extension()
        .and_then(|e| e.to_str())
        .map(str::to_ascii_lowercase)
        .as_deref()
    {
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        Some("avif") => "image/avif",
        Some("svg") => "image/svg+xml",
        Some("ico") => "image/x-icon",
        Some("bmp") => "image/bmp",
        Some("css") => "text/css; charset=utf-8",
        Some("js" | "mjs") => "text/plain; charset=utf-8", // never run local scripts
        Some("html" | "htm") => "text/plain; charset=utf-8", // never execute local HTML
        Some("txt" | "md" | "markdown") => "text/plain; charset=utf-8",
        Some("mp4") => "video/mp4",
        Some("webm") => "video/webm",
        Some("mp3") => "audio/mpeg",
        Some("pdf") => "application/pdf",
        _ => "application/octet-stream",
    }
}

/// Embedded third-party assets, served under `/__mdv/vendor/`.
///
/// mermaid is compiled in by the default `mermaid` cargo feature; a lean build
/// (`--no-default-features`) returns `None`, so diagram blocks stay as code.
/// TODO(bundling): katex.min.js, katex.min.css (+fonts) for math.
fn bundled_asset(name: &str) -> Option<(&'static str, &'static [u8])> {
    match name {
        #[cfg(feature = "mermaid")]
        "mermaid.min.js" => Some((
            "text/javascript; charset=utf-8",
            include_bytes!("../../../assets/vendor/mermaid.min.js"),
        )),
        _ => None,
    }
}

fn query_param<'a>(query: &'a str, key: &str) -> Option<&'a str> {
    query.split('&').find_map(|kv| {
        kv.split_once('=')
            .filter(|(k, _)| *k == key)
            .map(|(_, v)| v)
    })
}

/// Build the reply for `path` (URL path) and `query`. Mutates `state.current` when serving a document.
pub fn handle(state: &mut State, path: &str, query: &str) -> Reply {
    let mut r = route(state, path, query);
    r.csp = if r.app {
        app_csp(BASE, state.allow_remote_images)
    } else {
        FILE_CSP.to_string()
    };
    r
}

fn route(state: &mut State, path: &str, query: &str) -> Reply {
    match path {
        "/__mdv/style.css" => {
            return Reply::asset("text/css; charset=utf-8", page::CSS.as_bytes().to_vec())
        }
        "/__mdv/app.js" => {
            return Reply::asset(
                "text/javascript; charset=utf-8",
                page::JS.as_bytes().to_vec(),
            )
        }
        "/favicon.ico" => return Reply::text(404, "not found"),
        _ => {}
    }
    if let Some(name) = path.strip_prefix("/__mdv/vendor/") {
        return match bundled_asset(name) {
            Some((mime, b)) => Reply::asset(mime, b.to_vec()),
            None => Reply::text(404, "asset not bundled"),
        };
    }
    let theme = state.theme;
    let Some(root) = state.root.clone() else {
        return Reply::html(200, page::help_page(theme));
    };
    let full = match sandbox::resolve(&root, path) {
        Ok(p) => p,
        Err(SandboxError::NotFound) => return Reply::text(404, "not found"),
        Err(_) => return Reply::text(403, "forbidden"),
    };
    if full.is_dir() {
        return Reply::text(403, "directory");
    }
    if is_markdown(&full) {
        let raw = match query_param(query, "raw") {
            Some("1") => true,
            Some("0") => false,
            _ => state.raw_default,
        };
        let src = match sandbox::read_checked(&root, &full) {
            Ok(b) => String::from_utf8_lossy(&b).into_owned(),
            Err(e) => return Reply::html(500, page::error_page(theme, &e.to_string())),
        };
        state.current = Some(full.clone());
        let title = full
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        let html = if raw {
            page::raw_page(&title, &src, theme)
        } else {
            page::rendered_page(&title, &md_core::render(&src), theme)
        };
        return Reply::html(200, html);
    }
    match sandbox::read_checked(&root, &full) {
        Ok(body) => Reply {
            status: 200,
            mime: mime_for(&full),
            body,
            csp: String::new(),
            app: false,
        },
        Err(_) => Reply::text(404, "not found"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::fs;

    fn setup() -> (PathBuf, State) {
        use std::sync::atomic::{AtomicUsize, Ordering};
        static N: AtomicUsize = AtomicUsize::new(0);
        let d = std::env::temp_dir().join(format!(
            "mdv-serve-{}-{}",
            std::process::id(),
            N.fetch_add(1, Ordering::Relaxed)
        ));
        let _ = fs::remove_dir_all(&d);
        fs::create_dir_all(d.join("root")).unwrap();
        fs::write(d.join("root/a.md"), "# Title\n\ntext").unwrap();
        fs::write(d.join("root/i.png"), [1u8, 2, 3]).unwrap();
        fs::write(d.join("secret"), "s").unwrap();
        let root = d.join("root").canonicalize().unwrap();
        (
            d,
            State {
                root: Some(root),
                current: None,
                raw_default: false,
                theme: Theme::Auto,
                allow_remote_images: false,
            },
        )
    }

    #[test]
    fn serves_doc_modes() {
        let (_d, mut s) = setup();
        let r = handle(&mut s, "/a.md", "");
        assert_eq!(r.status, 200);
        assert!(String::from_utf8(r.body)
            .unwrap()
            .contains("data-mode=\"rendered\""));
        assert!(s.current.is_some());
        let r = handle(&mut s, "/a.md", "raw=1");
        assert!(String::from_utf8(r.body)
            .unwrap()
            .contains("data-mode=\"raw\""));
        s.raw_default = true;
        let r = handle(&mut s, "/a.md", "");
        assert!(String::from_utf8(r.body)
            .unwrap()
            .contains("data-mode=\"raw\""));
        let r = handle(&mut s, "/a.md", "raw=0");
        assert!(String::from_utf8(r.body)
            .unwrap()
            .contains("data-mode=\"rendered\""));
    }

    #[test]
    fn serves_assets_and_blocks_escape() {
        let (_d, mut s) = setup();
        let r = handle(&mut s, "/i.png", "");
        assert_eq!((r.status, r.mime), (200, "image/png"));
        assert_eq!(handle(&mut s, "/../secret", "").status, 403);
        assert_eq!(handle(&mut s, "/%2e%2e/secret", "").status, 403);
        assert_eq!(handle(&mut s, "/missing.png", "").status, 404);
        assert_eq!(handle(&mut s, "/__mdv/style.css", "").status, 200);
        assert_eq!(handle(&mut s, "/__mdv/vendor/nope.js", "").status, 404);
    }

    #[test]
    fn user_files_get_sandbox_csp_and_scripts_are_text() {
        let (d, mut s) = setup();
        fs::write(d.join("root/e.svg"), "<svg onload=alert(1)/>").unwrap();
        fs::write(d.join("root/e.js"), "alert(1)").unwrap();
        fs::write(d.join("root/e.html"), "<script>1</script>").unwrap();
        let r = handle(&mut s, "/e.svg", "");
        assert_eq!(r.mime, "image/svg+xml");
        assert_eq!(r.csp, FILE_CSP);
        assert!(r.csp.contains("sandbox") && r.csp.contains("default-src 'none'"));
        assert_eq!(
            handle(&mut s, "/e.js", "").mime,
            "text/plain; charset=utf-8"
        );
        assert_eq!(
            handle(&mut s, "/e.html", "").mime,
            "text/plain; charset=utf-8"
        );
        assert_eq!(handle(&mut s, "/i.png", "").csp, FILE_CSP);
    }

    #[test]
    fn app_pages_get_app_csp() {
        let (_d, mut s) = setup();
        for p in ["/a.md", "/__mdv/app.js", "/__mdv/style.css", "/nope-404.md"] {
            let r = handle(&mut s, p, "");
            assert!(r.csp.contains("script-src 'self'"), "{p}");
            assert!(r.csp.contains("frame-ancestors 'none'"), "{p}");
            assert!(!r.csp.contains("https:"), "{p}");
        }
        s.allow_remote_images = true;
        let r = handle(&mut s, "/a.md", "");
        assert!(r.csp.contains("img-src 'self'") && r.csp.contains("data: https:"));
    }

    #[test]
    fn nav_accepts_only_exact_origin_markdown() {
        for base in ["mdv://localhost", "http://mdv.localhost"] {
            let c = |p: &str| classify_nav(&format!("{base}{p}"), base);
            assert_eq!(c("/a.md"), Nav::Internal);
            assert_eq!(c("/sub/A%20b.MD#frag"), Nav::Internal);
            assert_eq!(c("/a.md?raw=1"), Nav::Internal);
            assert_eq!(c("/"), Nav::Internal);
            assert_eq!(c(""), Nav::Internal);
            assert_eq!(c("/dir/"), Nav::Internal);
            assert_eq!(c("/evil.svg"), Nav::Deny);
            assert_eq!(c("/x.html"), Nav::Deny);
            assert_eq!(c("/x.png?a=.md"), Nav::Deny);
            assert_eq!(c("/x.svg#.md"), Nav::Deny);
            assert_eq!(c("/__mdv/app.js"), Nav::Deny);
            assert_eq!(c("/noext"), Nav::Deny);
        }
        let b = "http://mdv.localhost";
        assert_eq!(
            classify_nav("http://mdv.localhost.evil.com/", b),
            Nav::External
        );
        assert_eq!(
            classify_nav("http://mdv.localhost@evil.com/", b),
            Nav::External
        );
        assert_eq!(
            classify_nav("http://mdv.localhost:8080/a.md", b),
            Nav::External
        );
        assert_eq!(
            classify_nav("http://mdv.localhost.evil.com/a.md", b),
            Nav::External
        );
        assert_eq!(classify_nav("https://mdv.localhost/a.md", b), Nav::External);
        let b = "mdv://localhost";
        assert_eq!(classify_nav("mdv://localhost.evil.com/a.md", b), Nav::Deny);
        assert_eq!(classify_nav("mdv://localhost@evil.com/a.md", b), Nav::Deny);
        assert_eq!(classify_nav("mdv://localhost:1/a.md", b), Nav::Deny);
        assert_eq!(classify_nav("https://example.com/", b), Nav::External);
        assert_eq!(classify_nav("mailto:a@b.c", b), Nav::External);
        assert_eq!(classify_nav("file:///etc/passwd", b), Nav::Deny);
        assert_eq!(classify_nav("javascript:alert(1)", b), Nav::Deny);
        assert_eq!(classify_nav("about:blank", b), Nav::Internal);
    }

    #[test]
    fn ipc_allowlist() {
        for b in ["http://mdv.localhost", "mdv://localhost"] {
            let ok = format!("{b}/a.md?raw=1");
            assert_eq!(ipc_action_for(b, &ok, "print"), Some(IpcAction::Print));
            assert_eq!(
                ipc_action_for(b, &format!("{b}/"), "print"),
                Some(IpcAction::Print)
            );
            for body in ["", "Print", "print ", "print\n", "PRINT", "open", "print;x"] {
                assert_eq!(ipc_action_for(b, &ok, body), None, "{body:?}");
            }
            for url in [
                "https://example.com/",
                "about:blank",
                "",
                "file:///etc/passwd",
                "http://mdv.localhost.evil.com/",
                "http://mdv.localhost@evil.com/",
                "mdv://localhost.evil.com/a.md",
                "mdv://localhost@evil.com/a.md",
                "javascript:print",
            ] {
                if url.starts_with(b) {
                    continue;
                }
                assert_eq!(ipc_action_for(b, url, "print"), None, "{url:?}");
            }
        }
        assert_eq!(ipc_action("https://evil.example/", "print"), None);
        assert_eq!(
            ipc_action(&format!("{BASE}/x.md"), "print"),
            Some(IpcAction::Print)
        );
    }

    #[test]
    fn doc_ids_cannot_hijack_ui_ids() {
        let (d, mut s) = setup();
        fs::write(
            d.join("root/c.md"),
            "# find\n\n<div id=find>x</div>\n\n# toc\n",
        )
        .unwrap();
        let html = String::from_utf8(handle(&mut s, "/c.md", "").body).unwrap();
        assert!(html.contains("id=\"find\""), "doc ids are preserved");
        assert_eq!(html.matches("id=\"mdv-find\"").count(), 1);
        for id in page::UI_IDS {
            assert!(id.starts_with("mdv-"));
            assert!(html.matches(&format!("id=\"{id}\"")).count() <= 1, "{id}");
        }
    }

    #[test]
    fn no_root_shows_help() {
        let mut s = State {
            root: None,
            current: None,
            raw_default: false,
            theme: Theme::Auto,
            allow_remote_images: false,
        };
        let r = handle(&mut s, "/", "");
        assert!(String::from_utf8(r.body)
            .unwrap()
            .contains("Drop a Markdown file"));
    }

    #[cfg(feature = "mermaid")]
    #[test]
    fn serves_bundled_mermaid() {
        let (_d, mut s) = setup();
        let r = handle(&mut s, "/__mdv/vendor/mermaid.min.js", "");
        assert_eq!((r.status, r.mime), (200, "text/javascript; charset=utf-8"));
        assert!(r.body.len() > 1_000_000, "mermaid bundle looks truncated");
        let head = String::from_utf8_lossy(&r.body[r.body.len() - 200..]).into_owned();
        assert!(
            head.contains("globalThis[\"mermaid\"]"),
            "bundle must export global mermaid"
        );
    }

    #[cfg(not(feature = "mermaid"))]
    #[test]
    fn lean_build_has_no_mermaid() {
        let (_d, mut s) = setup();
        assert_eq!(
            handle(&mut s, "/__mdv/vendor/mermaid.min.js", "").status,
            404
        );
    }

    #[test]
    fn mermaid_script_only_requested_for_diagram_docs() {
        let (d, mut s) = setup();
        fs::write(d.join("root/d.md"), "```mermaid\ngraph TD; A-->B;\n```\n").unwrap();
        let with = String::from_utf8(handle(&mut s, "/d.md", "").body).unwrap();
        assert!(with.contains("data-mermaid=\"1\""));
        assert!(
            with.contains("mermaid"),
            "diagram source must be present for the client renderer"
        );
        let without = String::from_utf8(handle(&mut s, "/a.md", "").body).unwrap();
        assert!(!without.contains("data-mermaid=\"1\""));
    }
}
